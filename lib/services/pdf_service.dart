  // ─────────────────────────────────────────
  // PDF Export — uses built-in fonts (no internet needed)
  // ─────────────────────────────────────────
  static Future<void> exportPdf({
    required String title,
    required String content,
    required BuildContext context,
    Uint8List? signatureBytes,
  }) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final logoPath = prefs.getString('logoPath');
      
      final pdf = pw.Document();

      // Use built-in Helvetica — no network download needed
      final font = pw.Font.helvetica();
      final boldFont = pw.Font.helveticaBold();
      final obliqueFont = pw.Font.helveticaOblique();

      // Strip AI preamble and inline markdown for clean PDF output
      final cleanContent = _stripMarkdown(_cleanAiContent(content));

      pw.MemoryImage? logoImage;
      if (logoPath != null && logoPath.isNotEmpty) {
        final logoFile = File(logoPath);
        if (logoFile.existsSync()) {
          logoImage = pw.MemoryImage(logoFile.readAsBytesSync());
        }
      }

      pw.MemoryImage? signatureImage;
      if (signatureBytes != null && signatureBytes.isNotEmpty) {
        signatureImage = pw.MemoryImage(signatureBytes);
      }

      pdf.addPage(
        pw.MultiPage(
          pageTheme: pw.PageTheme(
            pageFormat: PdfPageFormat.a4,
            margin: const pw.EdgeInsets.symmetric(horizontal: 50, vertical: 40),
            buildBackground: (ctx) {
              if (logoImage != null) {
                return pw.FullPage(
                  ignoreMargins: true,
                  child: pw.Center(
                    child: pw.Opacity(
                      opacity: 0.04,
                      child: pw.Image(
                        logoImage,
                        width: 260,
                        height: 260,
                        fit: pw.BoxFit.contain,
                      ),
                    ),
                  ),
                );
              }
              return pw.SizedBox();
            },
          ),
          header: (ctx) => pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  if (logoImage != null)
                    pw.Row(
                      children: [
                        pw.Image(
                          logoImage,
                          height: 24,
                          width: 24,
                          fit: pw.BoxFit.contain,
                        ),
                        pw.SizedBox(width: 8),
                        pw.Text('KOMPLI',
                            style: pw.TextStyle(
                                font: boldFont,
                                fontSize: 14,
                                color: const PdfColor.fromInt(0xFF008751),
                                letterSpacing: 2)),
                      ],
                    )
                  else
                    pw.Text('KOMPLI',
                        style: pw.TextStyle(
                            font: boldFont,
                            fontSize: 16,
                            color: const PdfColor.fromInt(0xFF008751),
                            letterSpacing: 2)),
                  pw.Text('Legal Document',
                      style: pw.TextStyle(
                          font: obliqueFont,
                          fontSize: 10,
                          color: PdfColors.grey600)),
                ],
              ),
              pw.Divider(
                  color: const PdfColor.fromInt(0xFF008751), thickness: 1.5),
              pw.SizedBox(height: 6),
            ],
          ),
          footer: (ctx) => pw.Column(
            children: [
              pw.Divider(color: PdfColors.grey300, thickness: 0.5),
              pw.SizedBox(height: 4),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text('Generated by Kompli — Nigerian SME Legal Assistant',
                      style: pw.TextStyle(
                          font: obliqueFont,
                          fontSize: 8,
                          color: PdfColors.grey500)),
                  pw.Text('Page ${ctx.pageNumber} of ${ctx.pagesCount}',
                      style: pw.TextStyle(
                          font: font, fontSize: 8, color: PdfColors.grey500)),
                ],
              ),
            ],
          ),
          build: (ctx) => [
            pw.Text(title.toUpperCase(),
                style: pw.TextStyle(
                    font: boldFont,
                    fontSize: 20,
                    color: const PdfColor.fromInt(0xFF001F3F),
                    letterSpacing: 0.5)),
            pw.SizedBox(height: 6),
            pw.Divider(color: PdfColors.grey400, thickness: 0.5),
            pw.SizedBox(height: 18),
            ..._buildPdfContent(cleanContent, font, boldFont),
            pw.SizedBox(height: 48),
            pw.Divider(color: PdfColors.grey600),
            pw.SizedBox(height: 16),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                _signatureBlock(font, 'Party A Signature', signatureImage: signatureImage),
                _signatureBlock(font, 'Party B Signature'),
              ],
            ),
          ],
        ),
      );

      await Printing.sharePdf(
        bytes: await pdf.save(),
        filename: '${_sanitizeFilename(title)}_Kompli.pdf',
      );
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('PDF export failed: $e'),
            backgroundColor: Colors.redAccent,
          ),
        );
      }
    }
  }

  // ─────────────────────────────────────────
  // DOCX Export — builds a proper .docx (OOXML) file
  // ─────────────────────────────────────────
  static Future<void> exportDocx({
    required String title,
    required String content,
    required BuildContext context,
  }) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final companyName = prefs.getString('companyName');
      final rcNumber = prefs.getString('rcNumber');
      final tin = prefs.getString('tin');
      final address = prefs.getString('address');
      final industry = prefs.getString('industry');

      // Strip AI preamble before building DOCX
      final cleanContent = _cleanAiContent(content);
      final bytes = _buildDocx(
        title,
        cleanContent,
        companyName: companyName,
        rcNumber: rcNumber,
        tin: tin,
        address: address,
        industry: industry,
      );

      // Write to temp file
      final dir = await getTemporaryDirectory();
      final filename = '${_sanitizeFilename(title)}_Kompli.docx';
      final file = File('${dir.path}/$filename');
      await file.writeAsBytes(bytes);

      // Share the file
      await Share.shareXFiles(
        [XFile(file.path, mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document')],
        subject: title,
      );
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('DOCX export failed: $e'),
            backgroundColor: Colors.redAccent,
          ),
        );
      }
    }
  }

